const LANGUAGE_KEY = 'neurotremor_lang';

export function getCurrentLanguage(): LanguageCode {
  if (typeof window === 'undefined') return 'en';
  const saved = localStorage.getItem(LANGUAGE_KEY) as LanguageCode;
  if (saved && translations[saved]) return saved;
  return 'en';
}

export function setCurrentLanguage(lang: LanguageCode) {
  if (typeof window !== 'undefined') {
    localStorage.setItem(LANGUAGE_KEY, lang);
    window.dispatchEvent(new Event('neurotremor_lang_changed'));
  }
}

export function useLanguage() {
  const [lang, setLang] = useState<LanguageCode>(getCurrentLanguage());

  useEffect(() => {
    const handleLangChange = () => {
      setLang(getCurrentLanguage());
    };
    window.addEventListener('neurotremor_lang_changed', handleLangChange);
    return () => {
      window.removeEventListener('neurotremor_lang_changed', handleLangChange);
    };
  }, []);

  const t = (key: string): string => {
    return translations[lang]?.[key] || translations['en']?.[key] || key;
  };

  const changeLanguage = (newLang: LanguageCode) => {
    setCurrentLanguage(newLang);
    setLang(newLang);
  };

  return { lang, setLang: changeLanguage, t, LANGUAGES };
}
